#include <stdio.h>

void	ft_swap(int *a, int *b)
{
	int	swp;

	swp = *a;
	*a = *b;
	*b = swp;
}

int	main(void)
{
	int	x;
	int	y;

	x = 10;
	y = 20;
	ft_swap(&x, &y);
	printf("%d %d", x, y);
	return(0);
}

