#include <stdio.h>

char	*ft_strcpy(char *dest, char *src)
{
	int	i;

	i = 0;
	while (src[i] != '\0')
	{
		dest[i] = src[i];
		i++;
	}
	dest[i] = '\0';
	return (dest);
}

int	main(void)
{
	char	origen[] = "hola";
	char	destino[] = "adios";

	ft_strcpy(destino, origen);
	printf("%s\n", origen);
	printf("%s\n", destino);

	return(0);
}
